/// How service names are compared: an account's issuer, a backup-code service's name and
/// a logo or directory entry match when they share a key. "GitHub", "GitHub, Inc.",
/// "github.com" and "https://github.com/login" all share "github".
library;

/// Lowercase, without accents or surrounding space, as JavaScript's
/// `s.normalize('NFD').replace(/\p{M}+/gu, '').toLowerCase().trim()` leaves it.
String fold(String s) {
  final unaccented = StringBuffer();
  for (final rune in s.runes) {
    _unaccent(rune, unaccented);
  }
  return jsTrim(jsLowerCase(unaccented.toString()));
}

/// [s] lowercased as JavaScript's `toLowerCase()` does it. Dart's leaves out the two rules
/// of Unicode's full case mapping that apply to lowercase in every language: U+0130 'İ'
/// becomes "i" and a combining dot above, and a capital sigma that ends a word becomes
/// the final sigma U+03C2. Dart's case tables are also older: capitals added since about
/// Unicode 6 (Cherokee, Georgian Mtavruli, Osage, Adlam and a few dozen others) stay as
/// they are. None of them can be part of a key.
String jsLowerCase(String s) => s.replaceAll('\u{130}', 'i\u{307}').replaceAll(_finalSigma, '\u{3c2}').toLowerCase();

/// [s] without the white space around it, as JavaScript's `trim()` leaves it: Dart's
/// `trim()` also removes U+0085.
String jsTrim(String s) => s.replaceAll(_edgeSpace, '');

/// Only the letters and digits: "GitHub, Inc." and "git-hub inc" both become "githubinc".
String squash(String s) => s.replaceAll(_notLetterOrDigit, '');

// Words an issuer tacks onto the brand: legal forms ("Proton AG", "GitHub, Inc.") and generic
// labels ("Apple ID", "Epic Games Account"). Only stripped as separate words, so "Visa" keeps "sa".
final _trailingWords = RegExp(
  r'(?:[\s,]+(?:inc|llc|ltd|limited|corp|corporation|gmbh|ggmbh|ag|sa|sas|sarl|plc|bv|ab|oy|pty|srl|account|accounts|id|login|2fa|mfa|sso)\.?)+$',
);
// Public suffixes worth knowing by name; a domain ending in anything else loses its last label.
final _suffix = RegExp(
  r'\.(?:co\.uk|org\.uk|com\.au|co\.jp|com\.br|co\.nz|com|net|org|io|co|me|app|dev|ai|gg|tv|us|eu|uk|de|fr|nl|be|ch|at|it|es|se|pl|ca|au|jp|info|biz|xyz)$',
);
final _domain = RegExp(r'^[a-z0-9-]+(?:\.[a-z0-9-]+)+$');
final _url = RegExp(r'^[a-z][a-z0-9+.-]*:\/\/([^/?#]*).*$');
final _qualifier = RegExp(r'\s*\([^()]*\)$');
final _www = RegExp(r'^www\.');
final _notLetterOrDigit = RegExp('[^a-z0-9]+');
// JavaScript's trim() takes exactly what \s matches.
final _edgeSpace = RegExp(r'^\s+|\s+$');
// Unicode's Final_Sigma condition: a cased letter before, and none after, past case-ignorable ones.
final _finalSigma = RegExp(r'(?<=\p{Cased}\p{Case_Ignorable}*)\u{3a3}(?!\p{Case_Ignorable}*\p{Cased})', unicode: true);

/// The keys a name may be filed under, most specific first.
List<String> keysFor(String name) {
  var s = fold(name)
      .replaceFirstMapped(_url, (m) => m[1]!) // a URL counts as its host
      .replaceFirst(_qualifier, '') // "GitHub (work)"
      .replaceFirst(_www, '');
  final keys = [squash(s)];
  s = s.replaceFirst(_trailingWords, '');
  keys.add(squash(s));
  if (_domain.hasMatch(s)) {
    // "accounts.google.com" → "google.com", then "google"; "eu.battle.net" → "battle.net"
    final suffix = _suffix.firstMatch(s)?[0] ?? s.substring(s.lastIndexOf('.'));
    final label = s.substring(0, s.length - suffix.length).split('.').last;
    keys
      ..add(squash(label + suffix))
      ..add(squash(label));
  } else {
    keys.add(squash(s.replaceFirst(_suffix, '')));
  }
  return [
    for (final key in keys)
      if (key.isNotEmpty) key,
  ];
}

/// True when two names are filed under a common key, i.e. are the same service.
bool sameService(String a, String b) {
  final keys = keysFor(a).toSet();
  return keysFor(b).any(keys.contains);
}

/// Writes what is left of [rune] once NFD has decomposed it and the marks are gone:
/// nothing for a mark, the base character from the table below, a Hangul syllable's
/// letters, or the character itself.
void _unaccent(int rune, StringBuffer out) {
  if (rune < 0xc0) {
    out.writeCharCode(rune);
  } else if (rune >= 0xac00 && rune <= 0xd7a3) {
    // Hangul syllables decompose by rule (Unicode, section 3.12).
    final index = rune - 0xac00;
    out
      ..writeCharCode(0x1100 + index ~/ 588)
      ..writeCharCode(0x1161 + index % 588 ~/ 28);
    if (index % 28 != 0) out.writeCharCode(0x11a7 + index % 28);
  } else if (!_isMark(rune)) {
    out.writeCharCode(_foldTable[rune] ?? rune);
  }
}

/// Each decomposable character's base character, from [_foldRuns]; built on first use.
final Map<int, int> _foldTable = {
  for (final (start, targets) in _foldRuns)
    for (final (i, rune) in targets.runes.indexed) start + i: rune,
};

/// Whether [rune] is a combining mark (\p{M}), by binary search of [_markRanges].
bool _isMark(int rune) {
  var low = 0;
  var high = _markRanges.length ~/ 2 - 1;
  while (low <= high) {
    final mid = (low + high) ~/ 2;
    if (rune < _markRanges[2 * mid]) {
      high = mid - 1;
    } else if (rune > _markRanges[2 * mid + 1]) {
      low = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

